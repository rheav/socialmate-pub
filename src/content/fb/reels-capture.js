  async function performReelAction(id, action, language) {
    const scope = currentSurface();
    collect();
    if (!id || !(scope === `reel:${id}` || (scope?.startsWith('profile:') && tiles.has(id))))
      throw new Error('O reel mudou. Tente novamente.');
    const rec = recordOf(id);
    if (!rec.id) throw new Error('Os dados deste reel ainda estão carregando.');
    if (scope.startsWith('reel:')) {
      if (Date.now() - routeChangedAt < 400 || !fbPlayerMatches(rec, activeVideo(), id))
        throw new Error('Aguarde o player carregar este reel.');
    }
    if (action === 'copy') {
      await navigator.clipboard.writeText(`https://www.facebook.com/reel/${id}`);
      return { ok: true };
    }
    if (action === 'save') {
      const res = await chrome.runtime.sendMessage({type:'FBW_SAVED_TOGGLE',entry:fbReelEntry(rec)});
      if (!res?.ok) throw new Error(res?.error || 'Falha ao salvar');
      res.saved ? savedIds.add(id) : savedIds.delete(id);
      return res;
    }
    const running = voices.get(id);
    if (action === 'voice' && running && !['done','error','cancelled'].includes(running.phase)) {
      const res = await chrome.runtime.sendMessage({type:'FBW_CANCEL_VOICE',jobId:running.jobId});
      if (!res?.ok) throw new Error(res?.error || 'Falha ao cancelar');
      return res;
    }
    const key = `${id}:${action}`;
    if (jobs.get(key)?.busy) throw new Error('Este trabalho já está em andamento.');
    const msg = fbReelJob(rec, action, language || await getTxLang());
    jobs.set(key,{busy:true});
    try {
      const res = await chrome.runtime.sendMessage(msg);
      if (!res || res.ok === false || (['transcribe','voice'].includes(action) && !res.started))
        throw new Error(res?.error || 'Não foi possível iniciar a ação');
      if (action === 'voice' && !voices.has(id)) voices.set(id,{...msg,phase:'fetch',pct:0});
      if (action !== 'transcribe') jobs.set(key,{done:true});
      return {ok:true,...res};
    } catch(e) { jobs.set(key,{error:e.message}); throw e; }
  }
