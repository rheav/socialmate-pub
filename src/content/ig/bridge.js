  // ---- progress bar ----------------------------------------------------
  // One bar per player. The FILL is a Web Animation: the browser interpolates a
  // transform off the main thread for the whole remaining runtime, so nothing
  // here runs per frame — measured drift against the media clock is 15-29 ms.
  //
  // The listeners below only start, stop and rebuild that animation. `timeupdate`
  // is a sanity check, not a driver: Instagram fires it ~4x/s regardless, and a
  // reel that LOOPS shows up there as a jump backwards, which is a rebuild.
  function attachVideoBar(video) {
    const bar = document.createElement("div");
    bar.className = "sw-bar";
    const track = document.createElement("div");
    track.className = "sw-bar-track";
    const buf = document.createElement("div");
    buf.className = "sw-bar-buf";
    const fill = document.createElement("div");
    fill.className = "sw-bar-fill";
    track.append(buf, fill);
    bar.appendChild(track);

    let anim = null;
    const stopAnim = () => { if (anim) { anim.cancel(); anim = null; } };
    const paint = (frac) => { fill.style.transform = `scaleX(${Math.min(1, Math.max(0, frac))})`; };

    function rebuild() {
      stopAnim();
      const spec = barAnimationSpec(video.currentTime, video.duration, video.playbackRate);
      if (!spec) { paint(video.duration ? video.currentTime / video.duration : 0); return; }
      paint(spec.from);
      if (video.paused) return; // a paused video gets a static fill, no animation
      anim = fill.animate(
        [{ transform: `scaleX(${spec.from})` }, { transform: "scaleX(1)" }],
        { duration: spec.durationMs, easing: "linear", fill: "forwards" },
      );
    }
    // Where the bar THINKS playback is, read back from the animation itself.
    function barTime() {
      if (!anim || video.duration <= 0) return video.currentTime;
      const spec = anim.effect.getTiming();
      const elapsed = (anim.currentTime || 0) / 1000;
      return video.duration - (spec.duration / 1000) * video.playbackRate + elapsed * video.playbackRate;
    }
    function onTimeUpdate() {
      if (!anim) { if (video.duration > 0) paint(video.currentTime / video.duration); return; }
      const what = barResync(barTime(), video.currentTime);
      if (what === "restart") rebuild();
      else if (what === "nudge") anim.currentTime += (video.currentTime - barTime()) * 1000;
    }
    function onProgress() {
      if (!video.buffered.length || !(video.duration > 0)) return;
      buf.style.transform = `scaleX(${video.buffered.end(video.buffered.length - 1) / video.duration})`;
    }

    // Scrubbing. The whole clip buffers within seconds (measured), so a seek
    // anywhere lands instantly; pointer capture keeps the drag alive even when it
    // leaves the bar, which is what makes it feel like a real scrubber.
    let dragging = false;
    const seekTo = (clientX) => {
      const t = seekTimeFromPointer(clientX, track.getBoundingClientRect(), video.duration);
      if (t == null) return;
      video.currentTime = t;
      paint(t / video.duration);
    };
    bar.addEventListener("pointerdown", (e) => {
      e.preventDefault();
      e.stopPropagation(); // never let the tap reach Instagram's play/pause layer
      dragging = true;
      bar.classList.add("sw-bar-drag");
      bar.setPointerCapture?.(e.pointerId);
      stopAnim();
      seekTo(e.clientX);
    });
    bar.addEventListener("pointermove", (e) => { if (dragging) { e.preventDefault(); seekTo(e.clientX); } });
    const endDrag = (e) => {
      if (!dragging) return;
      dragging = false;
      bar.classList.remove("sw-bar-drag");
      bar.releasePointerCapture?.(e.pointerId);
      rebuild();
    };
    bar.addEventListener("pointerup", endDrag);
    bar.addEventListener("pointercancel", endDrag);
    // Clicks are swallowed too: Instagram toggles playback on the pointer
    // sequence, and a scrub must not double as a pause.
    bar.addEventListener("click", (e) => { e.preventDefault(); e.stopPropagation(); });

    const onPlay = rebuild;
    const onPause = () => { stopAnim(); if (video.duration > 0) paint(video.currentTime / video.duration); };
    const onSeeked = () => { if (!dragging) rebuild(); };
    const onMeta = () => { rebuild(); onProgress(); };
    video.addEventListener("play", onPlay);
    video.addEventListener("pause", onPause);
    video.addEventListener("seeked", onSeeked);
    video.addEventListener("ratechange", rebuild);
    video.addEventListener("loadedmetadata", onMeta);
    video.addEventListener("timeupdate", onTimeUpdate);
    video.addEventListener("progress", onProgress);

    onMeta();
    if (!video.paused) rebuild();

    bar.__detach = () => {
      stopAnim();
      video.removeEventListener("play", onPlay);
      video.removeEventListener("pause", onPause);
      video.removeEventListener("seeked", onSeeked);
      video.removeEventListener("ratechange", rebuild);
      video.removeEventListener("loadedmetadata", onMeta);
      video.removeEventListener("timeupdate", onTimeUpdate);
      video.removeEventListener("progress", onProgress);
    };
    return bar;
  }

